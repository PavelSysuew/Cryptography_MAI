/**
 * Режимы набивки (задание 2.4). Теория: ЛК-3, п. 9.
 * Пример для блока 8 байт, когда до полного блока не хватает 3 байт:
 */
enum class PaddingMode {
    Zeros,     // 00 00 00     - нули (в конспекте нет)
    AnsiX923,  // 00 00 03     - нули, последний байт = длина набивки
    PKCS7,     // 03 03 03     - N байт со значением N
    ISO10126,  // ?? ?? 03     - случайные байты, последний = длина набивки (в конспекте нет)
};
